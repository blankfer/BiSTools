"""BiSTools / dev / bossdata.py - writes Tools/BossData.lua, BiS> BOSSES' shipped list.

    python dev/bossdata.py <DungeonEncounter.csv> <Map.csv>

Both files are the WoW Forever client's OWN tables (DungeonEncounter and Map, build 1.60.1.70862), read as CSV from
wago.tools/db2/<Table>/csv?build=1.60.1.70862 (wago.tools serves the client's data files as they ship; nothing here
comes from a web page). Every boss name, its order and its encounter id are the game's own words.

What is kept: dungeons and raids (Map.InstanceType 1 or 2), the normal entries only (DifficultyID 0 or 1 - the rest
are seasonal copies of the same fights), one row per name, in the game's OrderIndex. Test maps are dropped.
A name that is a GROUP fight ("The Seven", "Ring of Law") cannot be targeted by one name: it is written group = true,
and the finder shows it, counts it and ticks it off when the fight ends, but never tries to target it.
"""
import csv
import sys

DROP_MAPS = {"0", "13", "2720", "3002"}        # no longer in use, the test dungeon, the Searing Basin's test boss, no map
GROUPS = {
    "Ring of Law", "The Lost Dwarves", "The Vault", "The Seven", "The Molten Core", "Mechanical Menagerie",
    "Atal'ai Defenders", "Silithid Royalty", "Twin Emperors", "The Four Horsemen", "Edge of Madness",
    "Three Little Wolves", "Hans and Greta", "Deathless Guardians", "Ravasaur Hunters", "Reborn Council",
    "Dreamscythe and Weaver", "Jammal'an and Ogom", "Morphaz and Hazzas",
}


def lua(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(enc_path, map_path):
    maps = {}
    with open(map_path, encoding="utf8") as fh:
        for r in csv.DictReader(fh):
            maps[r["ID"]] = r
    by = {}
    with open(enc_path, encoding="utf8") as fh:
        for r in csv.DictReader(fh):
            m = r["MapID"]
            if m in DROP_MAPS or r["DifficultyID"] not in ("0", "1"):
                continue
            mp = maps.get(m)
            if not mp or mp["InstanceType"] not in ("1", "2"):
                continue
            by.setdefault(m, []).append((int(r["OrderIndex"]), int(r["ID"]), r["Name_lang"]))
    out = [
        "-- BiSTools / Tools / BossData.lua - BiS> BOSSES' list. GENERATED by dev/bossdata.py - never edit by hand.",
        "--",
        "-- The WoW Forever client's OWN tables (DungeonEncounter + Map, build 1.60.1.70862, read as CSV through",
        "-- wago.tools, which serves the game's data files as they ship): every dungeon and raid by its instance map id",
        "-- (GetInstanceInfo's 8th answer), its bosses in the game's order, each with its encounter id (ENCOUNTER_END's",
        "-- first answer). group = a fight of several (\"The Seven\"): shown and ticked off, never targeted by name.",
        "local _, NS = ...",
        "NS.BossData = {",
    ]
    total = 0
    for m in sorted(by, key=int):
        rows, seen = [], set()
        for _, eid, name in sorted(by[m]):
            if name in seen:
                continue
            seen.add(name)
            rows.append((eid, name))
        mp = maps[m]
        kind = "raid" if mp["InstanceType"] == "2" else "dungeon"
        out.append("  [%s] = { name = %s, kind = \"%s\", bosses = {" % (m, lua(mp["MapName_lang"]), kind))
        for eid, name in rows:
            g = ", group = true" if name in GROUPS else ""
            out.append("    { id = %d, name = %s%s }," % (eid, lua(name), g))
            total += 1
        out.append("  } },")
    out.append("}")
    with open("Tools/BossData.lua", "w", encoding="utf8", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    print("Tools/BossData.lua: %d places, %d bosses" % (len(by), total))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
